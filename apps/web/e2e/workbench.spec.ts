import { test, expect } from '@playwright/test'

test('fixture: brief → corrected scope → ready estimate → independent approval → exact export → superseded', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('DEMO FIXTURE · LOCAL ONLY')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Client brief' })).toBeVisible()
  await expect(page.getByText('Pricing blocked', { exact: true })).toBeVisible()
  await expect(page.getByText('unknown quantity')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Preview approved draft' })).toBeDisabled()

  await page.getByRole('spinbutton', { name: 'Quantity' }).nth(1).fill('1')
  await page.getByRole('textbox', { name: /One unresolved requirement per line/ }).fill('')
  await page.getByRole('button', { name: /Save new revision & estimate/ }).click()
  await expect(page.getByText('Ready for review', { exact: true })).toBeVisible()
  await expect(page.getByText('IDR', { exact: false }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Request review' }).click()
  await expect(page.getByText('Pending review', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Awaiting reviewer' })).toBeDisabled()

  await page.getByLabel('Acting as').selectOption('reviewer')
  await page.getByRole('button', { name: /Approve exact revision/ }).click()
  await expect(page.getByText('Approved', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Preview approved draft/ }).click()
  await expect(page.getByText('READ-ONLY · r2')).toBeVisible()
  await expect(page.getByText('17000000 IDR minor units', { exact: false })).toBeVisible()
  const dl = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download .md' }).click()
  expect((await dl).suggestedFilename()).toMatch(/r2\.md$/)

  await page.getByLabel('Acting as').selectOption('operator')
  await page.getByRole('spinbutton', { name: 'Quantity' }).nth(1).fill('2')
  await page.getByRole('button', { name: /Save new revision & estimate/ }).click()
  await expect(page.getByText('Prior review superseded', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: /Preview approved draft/ })).toBeDisabled()
  await page.getByRole('button', { name: /Audit timeline/ }).click()
  await expect(page.getByText('review.approved')).toBeVisible()
})
test('fixture: manual intake starts unpriced and reviewer cannot edit', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /New brief/ }).click()
  await page.getByLabel('Project title').fill('Sable / studio launch')
  await page.getByLabel('Original client brief').fill('Please deliver two interior studies. We have sketches.')
  await page.getByRole('button', { name: /Create project/ }).click()
  await expect(page.getByRole('heading', { name: 'Sable / studio launch' })).toBeVisible()
  await expect(page.getByText('No deliverables yet.')).toBeVisible()
  await page.getByRole('button', { name: /Add deliverable/ }).click()
  await expect(page.getByRole('spinbutton', { name: 'Quantity' })).toBeVisible()
  await page.getByLabel('Acting as').selectOption('reviewer')
  await expect(page.getByRole('button', { name: /Add deliverable/ })).toBeDisabled()
  await expect(page.getByRole('button', { name: /Save first scope/ })).toBeDisabled()
})
test('keyboard skip link and focusable controls', async ({ page }) => {
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to workbench' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#main-content')).toBeFocused()
})
